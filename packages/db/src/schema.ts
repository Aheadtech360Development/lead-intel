// ---------- findings ----------
// PHASE 4. One row per §5 check per business — the result of every check that has been run,
// including the ones that ran and found nothing wrong. Storing the passes is not padding: §6.1's
// area score divides fired points by "points available from checks that actually ran", so a pass
// is what puts points into the denominator, and a check that could not run must be absent from
// both sides.
//
// That rule is enforced here by a CHECK constraint rather than left to application code:
//   fired          -> 0 < points <= max_points   (contributes to both sides)
//   passed         -> points = 0, max_points > 0 (contributes to the denominator only)
//   not_measured   -> points = 0, max_points = 0 (contributes to neither — spec §13)
//   not_applicable -> points = 0, max_points = 0 (contributes to neither)
// It is not possible to write a row where a blocked check quietly counts as a pass.
//
// check_id is text, not an enum, on purpose: the catalogue lives in packages/core's check
// registry, which is what every writer derives its IDs from, and adding a check there should not
// require a database migration. `area` is denormalised from the family (CHECK_FAMILY_TO_AREA) so
// the scoring query can group by area without a join or a CASE; it is null for the N family,
// which feeds Intent (§6.3) rather than any service area.

export const findings = pgTable(
  "findings",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    businessId: uuid("business_id")
      .notNull()
      .references(() => businesses.id),
    checkId: text("check_id").notNull(), // "W4", "K1", "S13", ... — see packages/core check registry
    family: checkFamilyEnum("family").notNull(),
    area: serviceAreaEnum("area"), // null for the N (Intent) family
    outcome: checkOutcomeEnum("outcome").notNull(),
    costClass: checkCostClassEnum("cost_class").notNull(),
    points: integer("points").notNull().default(0),
    maxPoints: integer("max_points").notNull().default(0),
    /** Plain-language sentence an operator can read on the business page and act on. */
    evidence: text("evidence"),
    /** The specific things found, e.g. which platforms were linked. Display and debugging only. */
    detail: jsonb("detail"),
    sourceName: text("source_name").notNull(), // "own_crawl" | "pagespeed" | "google_places" | ...
    runId: uuid("run_id").references(() => runs.id),
    measuredAt: timestamp("measured_at", { withTimezone: true }).notNull().defaultNow(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    // One current result per (business, check) — the same living-fact model as field_metadata.
    // Re-auditing a site replaces its findings; it does not accumulate a history of them.
    uniqueCheck: uniqueIndex("findings_business_check_unique").on(table.businessId, table.checkId),
    businessIdx: index("findings_business_id_idx").on(table.businessId),
    // The scoring query: every finding for a business, grouped by area.
    businessAreaIdx: index("findings_business_area_idx").on(table.businessId, table.area),
    runIdIdx: index("findings_run_id_idx").on(table.runId),
    pointsConsistent: check(
      "findings_points_match_outcome",
      sql`(
        (${table.outcome} in ('not_measured', 'not_applicable') and ${table.points} = 0 and ${table.maxPoints} = 0)
        or (${table.outcome} = 'passed' and ${table.points} = 0 and ${table.maxPoints} > 0)
        or (${table.outcome} = 'fired' and ${table.points} > 0 and ${table.points} <= ${table.maxPoints})
      )`,
    ),
  }),
);

