// ---------- run_grid_cells ----------
// PHASE 3. The per-cell detail behind runs' aggregate counters — one row per search point in
// the adaptive grid (packages/core/src/discovery/grid.ts), added for two reasons pre-build-
// risks-and-api-limits.md §2.1 calls out explicitly: resumability (a retried run can pick up
// cells still "pending" instead of re-paying for ones already "done") and honesty ("every cell
// that saturates must be recorded, so an incomplete search is visible rather than silently
// missing businesses"). parentCellId deliberately has no FK constraint, matching the existing
// businesses.mergedInto pattern above — it's an informational lineage pointer (which saturated
// cell this one was born from), not a relationship the database needs to enforce.

export const runGridCells = pgTable(
  "run_grid_cells",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    runId: uuid("run_id")
      .notNull()
      .references(() => runs.id),
    parentCellId: uuid("parent_cell_id"), // see comment above — no FK, informational only
    depth: smallint("depth").notNull(),
    centerLat: doublePrecision("center_lat").notNull(),
    centerLng: doublePrecision("center_lng").notNull(),
    radiusMeters: integer("radius_meters").notNull(),
    status: gridCellStatusEnum("status").notNull().default("pending"),
    resultCount: integer("result_count"), // null until searched
    searchedAt: timestamp("searched_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    runIdIdx: index("run_grid_cells_run_id_idx").on(table.runId),
    // The query the discovery task actually runs on resume: "pending cells for this run".
    runStatusIdx: index("run_grid_cells_run_status_idx").on(table.runId, table.status),
    parentCellIdx: index("run_grid_cells_parent_cell_id_idx").on(table.parentCellId),
  }),
);

// ---------- businesses ----------
// The core record. Deliberately does NOT carry domain / place_id / phone / fb_page_id as
// columns — those live only in identity_keys, per build guide §3.1: "look up by any key" must
// stay a single indexed query, and the unique constraint there is what enforces
// one-business-one-record at the database level, not application code.
//
// lat_rounded / lng_rounded / location_hash ARE duplicated here, deliberately: they are
// clustering fields for spatial candidate-matching during grid deduplication (spec §3.2), not
// a uniqueness-bearing identity key the way name_location is in identity_keys. Many businesses
// legitimately share a grid cell.

export const businesses = pgTable(
  "businesses",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    status: businessStatusEnum("status").notNull().default("active"),

    displayName: text("display_name").notNull(),
    nameNormalized: text("name_normalized"),

    websiteStatus: websiteStatusEnum("website_status").notNull().default("unclear"),

    latRounded: doublePrecision("lat_rounded"),
    lngRounded: doublePrecision("lng_rounded"),
    city: text("city"),
    state: text("state"),
    country: text("country").notNull().default("us"),
    locationHash: text("location_hash"),

    manualReviewStatus: boolean("manual_review_status").notNull().default(false),
    manualReviewReasons: manualReviewReasonEnum("manual_review_reasons").array(),

    exclusionFlag: boolean("exclusion_flag").notNull().default(false),

    claimedBy: uuid("claimed_by"), // references auth.users(id)
    claimedAt: timestamp("claimed_at", { withTimezone: true }),
    claimStatus: claimStatusEnum("claim_status").notNull().default("unclaimed"),
    claimReleaseAt: timestamp("claim_release_at", { withTimezone: true }),

    // ---- Scoring (spec §6), written by the scorer after every audit ----
    // Every one of these is nullable and stays null when nothing was measured well enough to
    // support it. §6.1: "An area judged on one working check is noise." A zero here would be a
    // claim — that we looked and found no problems — and these columns must never make that claim
    // on a business whose site we could not read.
    problemScore: doublePrecision("problem_score"), // §6.2, 0-100
    intentScore: integer("intent_score"), // §6.3, 0-100, capped
    tier: smallint("tier"), // §6.4, 1-4
    route: serviceRouteEnum("route"), // §6.5 — null when the winning area has no evidence
    routeReason: text("route_reason"), // why that route, or why there is none
    /** Per-area detail: score, fired/measured/possible points, coverage, enoughData. */
    areaScores: jsonb("area_scores"),
    scoredAt: timestamp("scored_at", { withTimezone: true }),

    // Passed the free-check gate (spec §9 Stage 5)? Null = not yet evaluated.
    passedGate: boolean("passed_gate"),

    mergedInto: uuid("merged_into"),
    mergedAt: timestamp("merged_at", { withTimezone: true }),

    discoveredInRun: uuid("discovered_in_run").references(() => runs.id),

    /**
     * Where this record was *created* — not every source that has since touched it.
     *
     * A business found by a Maps search and later topped up from a spreadsheet stays
     * `discovered`: the import added fields to it, it did not create it, and
     * `field_metadata.source_name` already records that per field. Keeping this to origin is what
     * makes "show me only what I imported" a question with one true answer.
     */
    origin: businessOriginEnum("origin").notNull().default("discovered"),
    /** Which uploaded file, for `origin = 'imported'`. Null everywhere else. */
    importBatchId: uuid("import_batch_id"),

    // ---- The operator's own category, assigned by their rules (see category_rules) ----
    category: text("category"),
    subcategory: text("subcategory"),
    /**
     * Which rule decided. Null means no rule matched, or the rule that matched has been deleted —
     * both of which mean the category should be re-evaluated rather than trusted.
     */
    categoryRuleId: uuid("category_rule_id"),
    categorisedAt: timestamp("categorised_at", { withTimezone: true }),

    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    mergedIntoFk: index("businesses_merged_into_idx").on(table.mergedInto),
    nameNormalizedIdx: index("businesses_name_normalized_idx").on(table.nameNormalized),
    locationHashIdx: index("businesses_location_hash_idx").on(table.locationHash),
    statusIdx: index("businesses_status_idx").on(table.status),
    // Added in Phase 2: the businesses_update RLS policy filters on claimed_by directly.
    claimedByIdx: index("businesses_claimed_by_idx").on(table.claimedBy),
    discoveredInRunIdx: index("businesses_discovered_in_run_idx").on(table.discoveredInRun),
    // §8.1: "Sorted by tier, then Problem score." That is the list's default ordering, so it is
    // the one query that must not table-scan as the dataset grows.
    tierProblemIdx: index("businesses_tier_problem_idx").on(table.tier, table.problemScore),
    routeIdx: index("businesses_route_idx").on(table.route),
    tierRange: check("businesses_tier_range", sql`${table.tier} is null or (${table.tier} between 1 and 4)`),
    problemScoreRange: check(
      "businesses_problem_score_range",
      sql`${table.problemScore} is null or (${table.problemScore} between 0 and 100)`,
    ),
    intentScoreRange: check(
      "businesses_intent_score_range",
      sql`${table.intentScore} is null or (${table.intentScore} between 0 and 100)`,
    ),
  }),
);

// ---------- identity_keys ----------
// The table build guide §3.1 exists specifically to explain. Any key resolves to its business
// in one indexed lookup; the unique constraint is what makes "one business, one record" a
// database guarantee instead of an application promise.

export const identityKeys = pgTable(
  "identity_keys",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    businessId: uuid("business_id")
      .notNull()
      .references(() => businesses.id),
    keyType: identityKeyTypeEnum("key_type").notNull(),
    keyValue: text("key_value").notNull(),
    // Rank is a fixed property of keyType (see IDENTITY_KEY_RANK in packages/shared) — stored
    // here too only to keep read queries index-only; packages/core is the single source of the
    // type -> rank mapping and must be what populates this column.
    rank: smallint("rank").notNull(),
    migratedFrom: uuid("migrated_from"), // set when this key moved here during a merge
    addedAt: timestamp("added_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    // THE constraint. A second business trying to claim an already-owned key fails here, and
    // that failure — Postgres error 23505 — is what triggers the late-merge decision
    // (packages/core/src/merge/merge.ts), never a pre-check SELECT (build guide §3.4: a
    // pre-check is a race between concurrent discovery workers).
    uniqueKey: uniqueIndex("identity_keys_type_value_unique").on(table.keyType, table.keyValue),
    businessIdx: index("identity_keys_business_id_idx").on(table.businessId),
    // Rank is meant to be a pure function of keyType (packages/shared IDENTITY_KEY_RANK) — this
    // constraint only catches the case where the application layer supplies a value outside the
    // possible range entirely; it cannot verify type<->rank consistency by itself.
    rankRange: check("identity_keys_rank_range", sql`${table.rank} >= 1 AND ${table.rank} <= 5`),
  }),
);

